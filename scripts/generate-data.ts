const wordMap = new Map<string, Word>();
for (const w of words) {
  const key = w.word.toLowerCase().trim();
  const existing = wordMap.get(key);
  if (existing) {
    const merged = Array.from(new Set([...existing.tags, ...w.tags]));
    existing.tags = merged;
    if (w.variants) existing.variants = [...(existing.variants ?? []), ...w.variants];
  } else {
    wordMap.set(key, { ...w, word: key });
  }
}

const wordsObj: Record<string, { display: string; tags: string[]; variants?: string[] }> = {};
for (const [key, w] of [...wordMap.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  wordsObj[key] = { display: w.display, tags: w.tags, variants: w.variants };
}

